static void cosmo_panel_write(struct mipi_dsi_multi_context *ctx,
			      const u8 *buf, size_t len)
{
	if (buf[0] < 0xb0)
		mipi_dsi_dcs_write_buffer_multi(ctx, buf, len);
	else
		mipi_dsi_generic_write_multi(ctx, buf, len);
}

static int cosmo_panel_on(struct cosmo_panel *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };
	static const u8 sleep_out[] = { MIPI_DCS_EXIT_SLEEP_MODE, 0x00 };
	static const u8 display_on[] = { MIPI_DCS_SET_DISPLAY_ON, 0x00 };
	size_t i = 0;

	while (i < ARRAY_SIZE(cosmo_nt36672_init)) {
		u8 len = cosmo_nt36672_init[i];

		cosmo_panel_write(&dsi_ctx, &cosmo_nt36672_init[i + 1], len);
		i += len + 1;
	}

	cosmo_panel_write(&dsi_ctx, sleep_out, sizeof(sleep_out));
	mipi_dsi_msleep(&dsi_ctx, 120);
	cosmo_panel_write(&dsi_ctx, display_on, sizeof(display_on));
	mipi_dsi_msleep(&dsi_ctx, 10);

	return dsi_ctx.accum_err;
}

/* Bias off in stock order (negative first), then report what the PMIC says. */
static void cosmo_panel_bias_off(struct cosmo_panel *ctx)
{
	struct device *dev = &ctx->dsi->dev;
	int ret;

	ret = regulator_disable(ctx->vsn);
	if (ret)
		dev_err(dev, "vsn disable failed: %d\n", ret);
	ret = regulator_disable(ctx->vsp);
	if (ret)
		dev_err(dev, "vsp disable failed: %d\n", ret);

	/* is_enabled reads the MT6370 DB_CTRL2 enable bits. */
	if (regulator_is_enabled(ctx->vsp) > 0 ||
	    regulator_is_enabled(ctx->vsn) > 0)
		dev_warn(dev, "panel bias still on after power-off\n");
	else
		dev_info(dev, "panel off, bias off\n");
}

static int cosmo_panel_prepare(struct drm_panel *panel)
{
	struct cosmo_panel *ctx = to_cosmo_panel(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	/* Stock resume_power: reset low, then bias on. */
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);

	ret = regulator_enable(ctx->vsp);
	if (ret) {
		dev_err(dev, "vsp enable failed: %d\n", ret);
		return ret;
	}
	ret = regulator_enable(ctx->vsn);
	if (ret) {
		dev_err(dev, "vsn enable failed: %d\n", ret);
		regulator_disable(ctx->vsp);
		return ret;
	}

	/* Stock lcm_poweron. */
	msleep(20);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	msleep(10);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	msleep(10);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	msleep(20);

	ret = cosmo_panel_on(ctx);
	if (ret) {
		dev_err(dev, "init sequence failed: %d\n", ret);
		cosmo_panel_bias_off(ctx);
		return ret;
	}

	dev_info(dev, "panel on\n");
	return 0;
}

static int cosmo_panel_unprepare(struct drm_panel *panel)
{
	struct cosmo_panel *ctx = to_cosmo_panel(panel);
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };
	static const u8 display_off[] = { MIPI_DCS_SET_DISPLAY_OFF };
	static const u8 sleep_in[] = { MIPI_DCS_ENTER_SLEEP_MODE };

	/* Stock lcm_suspend: table, then 10 ms. Errors do not stop power-off. */
	cosmo_panel_write(&dsi_ctx, display_off, sizeof(display_off));
	if (dsi_ctx.accum_err)
		dev_err(&ctx->dsi->dev, "display-off failed: %d\n", dsi_ctx.accum_err);
	msleep(50);
	dsi_ctx.accum_err = 0;
	cosmo_panel_write(&dsi_ctx, sleep_in, sizeof(sleep_in));
	if (dsi_ctx.accum_err)
		dev_err(&ctx->dsi->dev, "sleep-in failed: %d\n", dsi_ctx.accum_err);
	msleep(120);
	msleep(10);

	/* Stock suspend_power. Reset stays high, as stock. */
	cosmo_panel_bias_off(ctx);

	return 0;
}

