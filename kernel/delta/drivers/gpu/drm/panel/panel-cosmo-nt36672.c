/*
 * Planet Computers Cosmo Communicator panel: NT36672 controller, 1080x2160,
 * 4-lane DSI burst video mode.
 *
 * Stock reference (vendor kernel 4.4, LCM aeon_nt36672_fhd_dsi_vdo_x800_datong,
 * source file lcm/aeon_nt36672_fhd_dsi_vdo_x600_xinli): the init table below
 * is byte-identical to the tables compiled into the stock kernel and LK.
 * Power sequences follow the stock kernel binary:
 *
 *   on:  reset low, bias +5.4 V then -5.4 V (MT6370 DSV), reset
 *        0/20 ms/1/10 ms/0/10 ms/1/20 ms, init table, 0x11 + 120 ms,
 *        0x29 + 10 ms. DSI is already up in LP-11 (prepare_prev_first).
 *   off: 0x28 + 50 ms, 0x10 + 120 ms, 10 ms, bias -5.4 V off then +5.4 V
 *        off. Stock leaves reset high while the panel is off.
 *
 * Packet types as the stock DSI driver: command < 0xB0 as DCS, otherwise
 * as generic writes; all sent in low-power mode.
 */

